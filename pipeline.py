"""Run the full pipeline: raw/ -> clean SQLite -> docs/report.md + chart.

    python generate_raw_data.py   # once, creates raw/*.csv
    python pipeline.py
"""
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402
import pandas as pd  # noqa: E402

from etl.extract import extract  # noqa: E402
from etl.load import load  # noqa: E402
from etl.transform import transform  # noqa: E402

ROOT = Path(__file__).resolve().parent


def chart(kpis: pd.DataFrame, path: Path) -> None:
    plt.rcParams.update({"font.size": 10, "axes.spines.top": False, "axes.spines.right": False})
    fig, ax = plt.subplots(figsize=(8, 3.6))
    x = range(len(kpis))
    ax.bar([i - 0.2 for i in x], kpis["open_rate"], width=0.4, color="#c9d6ea", label="Open rate %")
    ax.bar([i + 0.2 for i in x], kpis["click_to_open_rate"], width=0.4, color="#1f4e8c", label="Click-to-open %")
    ax.set_xticks(list(x), kpis["campaign_name"], rotation=20, ha="right")
    ax.set_ylabel("%")
    ax.legend(frameon=False)
    ax.set_title("Engagement by campaign")
    fig.tight_layout()
    fig.savefig(path, dpi=160)
    plt.close(fig)


def main() -> None:
    raw = extract(ROOT / "raw")
    tables, stats = transform(raw)
    con = load(tables, ROOT / "campaigns.db")
    kpis = pd.read_sql("SELECT * FROM campaign_kpis", con)
    by_type = pd.read_sql(
        "SELECT campaign_type, ROUND(AVG(open_rate),1) AS avg_open_rate, "
        "ROUND(AVG(click_to_open_rate),1) AS avg_click_to_open_rate, "
        "ROUND(AVG(unsubscribe_rate),2) AS avg_unsubscribe_rate "
        "FROM campaign_kpis GROUP BY campaign_type ORDER BY avg_click_to_open_rate DESC", con)

    docs = ROOT / "docs"
    docs.mkdir(exist_ok=True)
    chart(kpis, docs / "engagement.png")
    lines = ["# Campaign report", "", "Generated by `pipeline.py` from synthetic data.", "",
             "## Data cleaning", ""]
    lines += [f"- {k.replace('_', ' ')}: {v:,}" for k, v in stats.items()]
    lines += ["", "## KPIs by campaign", "", kpis.to_markdown(index=False), "",
              "## KPIs by campaign type", "", by_type.to_markdown(index=False), ""]
    (docs / "report.md").write_text("\n".join(lines))
    print("\n".join(f"{k}: {v}" for k, v in stats.items()))
    print(kpis.to_string(index=False))


if __name__ == "__main__":
    main()
